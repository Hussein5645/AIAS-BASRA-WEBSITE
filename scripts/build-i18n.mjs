import {readFile,readdir,writeFile} from 'node:fs/promises';
const clean=value=>value.replace(/&amp;/g,'&').replace(/&quot;/g,'"').replace(/&#39;|&apos;/g,"'").replace(/&nbsp;/g,' ').replace(/\s+/g,' ').trim();
const catalog={};
for(const file of await readdir('.'))if(file.endsWith('.html')&&!file.includes('backup')){
 const html=await readFile(file,'utf8');for(const tag of html.matchAll(/<[^>]+\bdata-en="([^"]+)"[^>]*>/g)){const ar=/\bdata-ar="([^"]+)"/.exec(tag[0]);if(ar)catalog[clean(tag[1])]=clean(ar[1]);}
}
for(const file of await readdir('js'))if(file.endsWith('.js')&&!file.startsWith('i18n')){
 const text=await readFile('js/'+file,'utf8');for(const match of text.matchAll(/\btr\(\s*'((?:\\.|[^'\\])*)'\s*,\s*'((?:\\.|[^'\\])*)'\s*\)/g)){const decode=s=>s.replace(/\\'/g,"'").replace(/\\n/g,'\n').replace(/\\u([\da-f]{4})/gi,(_,x)=>String.fromCharCode(parseInt(x,16)));catalog[clean(decode(match[1]))]=decode(match[2]);}
}
Object.assign(catalog,JSON.parse(await readFile('data/translations-ar.json','utf8')));
await writeFile('js/i18n-catalog.js','// Shared Arabic UI catalog. Generated by scripts/build-i18n.mjs.\nexport default '+JSON.stringify(catalog,null,2)+';\n');
console.log('Prepared '+Object.keys(catalog).length+' Arabic UI translations.');
